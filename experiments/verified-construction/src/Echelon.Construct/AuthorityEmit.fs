/// Emits `Invoice.Authority.g.fs`: the decided values of accepted decisions
/// and the identities of unresolved questions, copied verbatim from the
/// admitted handoff, each marked with the ID it comes from.
///
/// This is handwritten *extension* generation, not Ordo's emitter: Ordo's
/// vocabulary has no operation that carries a decision parameter (a limit
/// amount, a role name), because states and commands carry no data in any
/// vocabulary. See LIMITATIONS.md, "Vocabulary gaps".
module Echelon.Construct.AuthorityEmit

open System
open System.Globalization
open Echelon.Construct.Handoff
open Echelon.Construct.Admission
open Echelon.Construct.Translate

[<Literal>]
let GeneratorName = "echelon.verified-construction"

[<Literal>]
let GeneratorVersion = "0.1.0"

[<Literal>]
let Marker = "// <auto-generated by echelon.verified-construction"

let Path = "src/Invoice.Slice/generated/Invoice.Authority.g.fs"

/// A string literal safe for any input: every character outside printable
/// ASCII, and the quote and backslash, are escaped.
let private literal (value: string) =
    let escape (c: char) =
        match c with
        | '"' -> "\\\""
        | '\\' -> "\\\\"
        | c when c >= ' ' && c <= '~' -> string c
        | c -> sprintf "\\u%04x" (int c)
    "\"" + (value |> Seq.map escape |> String.concat "") + "\""

/// One line of doc-comment prose; newlines collapse so text cannot leave the comment.
let private prose (value: string) = value.Replace("\r", " ").Replace("\n", " ")

let private sourceLine (s: SourceRef) =
    sprintf "Source: %s%s @ %s%s" s.Path (s.Locator |> Option.map (sprintf " %s") |> Option.defaultValue "") s.Revision
        (s.Sha256 |> Option.map (sprintf " (%s)") |> Option.defaultValue "")

let emit (handoffDigest: string) (admitted: AdmittedHandoff) (authority: SliceAuthority) : string =
    let h = handoffOf admitted
    let decision id = h.Decisions |> List.find (fun d -> d.Id = id)
    let limit = decision LimitDecision
    let boundary = decision BoundaryDecision
    let q = authority.VoidQuestion
    let header (d: Decision) =
        [ sprintf "    /// %s (accepted %s by %s): %s" d.Id (d.AuthorizedAt |> Option.defaultValue "?")
              (d.AuthorizedBy |> Option.map _.Id |> Option.defaultValue "?") (prose d.Statement)
          sprintf "    /// %s" (sourceLine d.Source) ]
    let lines =
        [ sprintf "%s/%s from handoff %s %s>" Marker GeneratorVersion h.HandoffId handoffDigest
          "// Decided values of accepted, human-authorized decisions and the identities of unresolved"
          "// questions, copied from the handoff. Regenerated by `construct`; edits are overwritten."
          ""
          "namespace Invoice.Slice"
          ""
          "open Echelon.Provenance"
          ""
          "/// Values fixed by the handoff's accepted decisions. No other source defines policy values."
          "[<RequireQualifiedAccess>]"
          sprintf "[<Authority(%s, %s, %s)>]" (literal LimitDecision) (literal BoundaryDecision) (literal q.Id)
          "module Authority ="
          "" ]
        @ header limit
        @ [ sprintf "    [<Authority(%s)>]" (literal LimitDecision)
            sprintf "    let decFin001Limit = %sm" (authority.Limit.ToString(CultureInfo.InvariantCulture))
            ""
            sprintf "    /// The refusal code %s names." LimitDecision
            sprintf "    [<Authority(%s)>]" (literal LimitDecision)
            sprintf "    let decFin001RefusalCode = %s" (literal authority.LimitRefusalCode)
            "" ]
        @ header boundary
        @ [ sprintf "    [<Authority(%s)>]" (literal BoundaryDecision)
            sprintf "    let decFin002Role = %s" (literal authority.PaymentsServiceRole)
            ""
            sprintf "    /// %s (%s, owner %s, permitted outcome refuse-and-record): %s" q.Id q.Status q.Owner (prose q.Question)
            sprintf "    [<Authority(%s)>]" (literal q.Id)
            sprintf "    let qFin001 = %s" (literal q.Id) ]
    (lines |> String.concat "\n") + "\n"
