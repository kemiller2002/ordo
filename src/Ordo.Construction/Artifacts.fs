/// What the engine produces: immutable descriptions, never effects.
module Ordo.Construction.Artifacts

/// The generator for vocabulary 1 plans. Its output for a given plan digest
/// never changes.
[<Literal>]
let GeneratorVersion = "ordo.construction/1"

/// The generator for vocabulary 2 plans. Tiers 1 and 2 have the same shape
/// as version 1; Tier 3 applies each effect's declared failure disposition
/// and reports the post-command state.
[<Literal>]
let GeneratorVersion2 = "ordo.construction/2"

/// The generator for vocabulary 3 plans: version 2 plus classified pairs. A
/// pair the plan leaves undecided is reported by Tier 2 as `Undecided`, never
/// refused by omission, and an extension with an undecided decision point
/// gets a decide obligation instead of an implement obligation.
[<Literal>]
let GeneratorVersion3 = "ordo.construction/3"

/// The generator for vocabulary 4 plans: version 3 plus typed refusal codes
/// and branching transitions. For a plan that uses neither, Tiers 1 to 3 are
/// version 3's output with only the generator name changed.
[<Literal>]
let GeneratorVersion4 = "ordo.construction/4"

/// The generator for vocabulary 5 plans: version 4 plus effect outcome
/// policies in Tier 3. A definitely failed effect is retried up to the plan's
/// count, then remains, proceeds, is compensated by host code or escalated;
/// an unknown outcome is reconciled by host code or escalated, never retried.
[<Literal>]
let GeneratorVersion5 = "ordo.construction/5"

/// The generator version a plan's vocabulary selects. The plan cannot choose
/// it any other way.
let generatorVersionFor (vocabularyVersion: string) =
    if vocabularyVersion = Ordo.Core.ConstructionPlan.VocabularyVersion5 then GeneratorVersion5
    elif vocabularyVersion = Ordo.Core.ConstructionPlan.VocabularyVersion4 then GeneratorVersion4
    elif vocabularyVersion = Ordo.Core.ConstructionPlan.VocabularyVersion3 then GeneratorVersion3
    elif vocabularyVersion = Ordo.Core.ConstructionPlan.VocabularyVersion2 then GeneratorVersion2
    else GeneratorVersion

/// The marker every generated file starts with. A host may replace a file at
/// a target path only if it carries this marker; anything else is
/// handwritten and is never overwritten.
[<Literal>]
let GeneratedMarker = "// <auto-generated by ordo.construction"

/// The accepted Four-Tier placement of a generated file. Tier 4 (Host) is
/// never generated: hosts own clocks, storage, networks and effects.
type Tier =
    | SemanticModel
    | Transition
    | Orchestration

type Ownership =
    /// Regenerated from the plan; replaced wholesale, never edited.
    | Generated
    /// Written by people; the engine emits a contract for it, never the file.
    | Handwritten

type Artifact =
    { Path: string
      Tier: Tier option
      Ownership: Ownership
      Content: string
      /// SHA-256 of the UTF-8 content.
      Digest: string
      /// Derived labels of the plan operations this artifact realizes.
      Operations: string list
      RequirementKeys: string list }

type ExtensionKind =
    | GuardPredicate
    | InvariantPredicate
    | CurrentTimePort
    | EffectPort
    /// Vocabulary 4: picks one target of a branching transition from a closed union.
    | SelectionFunction
    /// Vocabulary 5: asks whether an effect whose outcome was unknown landed.
    | ReconcilePort
    /// Vocabulary 5: undoes a definitely failed effect, on approved authority.
    | CompensatePort

/// A handwritten implementation the generated code requires and cannot
/// supply. Missing ones fail compilation; there is no permissive default.
type ExtensionContract =
    { Name: string
      Kind: ExtensionKind
      Ownership: Ownership
      Operations: string list
      RequirementKeys: string list }

type ObligationKind =
    /// Implement an extension contract.
    | Implement of contract: string
    /// The plan declared behavior it must not decide.
    | ResolveUnresolved of subject: string * question: string
    /// Vocabulary 2: the plan leaves what a failed or unknown outcome of this
    /// effect means unresolved. The generated orchestration returns a result
    /// case the host must handle explicitly until this is resolved.
    | ResolveEffectFailure of effect: string * subject: string * question: string
    /// Behavior compiles but is not verified by generation; independent
    /// verification (Dokimos) is still required.
    | VerifyIndependently of what: string
    /// Vocabulary 3: the requirements do not decide what a command does in a
    /// state. Generated code reports the pair as `Undecided` until it is decided.
    | ResolveUndecidedTransition of state: string * command: string * question: string
    /// Vocabulary 3: a decision point of an extension is undecided. The
    /// extension is not implementable until it is decided, so it gets this
    /// obligation instead of `Implement`.
    | DecideExtension of contract: string * point: string * question: string

type ConstructionObligation =
    { Id: string
      Kind: ObligationKind
      RequirementKeys: string list }

/// Expected outcome of one (state, command) pair, derived from the plan.
/// Structural, not independent behavioral acceptance evidence.
type StructuralCheck =
    { State: string
      Command: string
      Expected: string option
      /// Vocabulary 3: the pair is open, neither legal nor refused.
      Undecided: bool
      /// Vocabulary 4: the targets a branching transition may select; empty otherwise.
      Targets: string list }
