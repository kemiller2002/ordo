/// F# source emission for one finite-state workflow. Every token that reaches
/// the output is either fixed text written here, a grammar-checked semantic
/// name, a grammar-checked capability identifier, or the hex plan digest.
/// No requirement text, question, trace key or other plan prose is ever
/// rendered into code.
module internal Ordo.Construction.Emit

open Ordo.Core.ConstructionPlan
open Ordo.Construction.Naming

/// LF line endings and a single trailing newline, whatever the platform.
let private render (lines: string list) = String.concat "\n" lines + "\n"

let private indent n (lines: string list) =
    lines |> List.map (fun line -> if line = "" then "" else String.replicate n " " + line)

let private header (digest: string) (tier: string) =
    [ sprintf "// <auto-generated by ordo.construction/1 from %s>" digest
      sprintf "// %s. Regenerated from the construction plan; edits are overwritten." tier
      "// Handwritten behavior belongs in extension code, never in this file."
      "" ]

/// A capability literal. The plan grammar already restricts capability text
/// to ASCII words joined by . : - _; this re-check keeps the emitter safe on
/// its own terms rather than trusting the caller.
let private literal (text: string) =
    if text |> Seq.forall (fun ch -> System.Char.IsAsciiLetterOrDigit ch || ch = '.' || ch = ':' || ch = '-' || ch = '_') then
        "\"" + text + "\""
    else invalidArg "text" "capability text outside the emitter grammar"

let private union (doc: string) (name: string) (cases: string list) =
    [ "/// " + doc
      "[<RequireQualifiedAccess>]"
      "type " + name + " =" ]
    @ (cases |> List.map (fun case -> "    | " + case))
    @ [ "" ]

let private qualify typeName (name: SemanticName) = typeName + "." + name.Key

/// What the workflow needs, decided once from the plan.
type Shape =
    { Workflow: Workflow
      States: SemanticName list
      Commands: SemanticName list
      Guards: SemanticName list
      Invariants: SemanticName list
      Effects: SemanticName list
      HasClock: bool
      HasCapabilities: bool }

    member this.HasRules = not (List.isEmpty this.Guards && List.isEmpty this.Invariants)
    member this.HasPorts = this.HasClock || not (List.isEmpty this.Effects)

let shapeOf (w: Workflow) =
    { Workflow = w
      States = w.States |> List.map _.Name
      Commands = w.Commands
      Guards = w.Transitions |> List.collect (fun t -> t.Guards |> List.map _.Name) |> List.distinctBy _.Key |> List.sortBy _.Key
      Invariants = w.Invariants |> List.map _.Name
      Effects = w.Ports |> List.choose (fun p -> match p.Kind with TransitionEffectPort c -> Some c | CurrentTimePort -> None)
      HasClock = w.Ports |> List.exists (fun p -> p.Kind = CurrentTimePort)
      HasCapabilities = not (List.isEmpty w.Capabilities) }

let private list (items: string list) =
    match items with
    | [] -> "[]"
    | _ -> "[ " + String.concat "; " items + " ]"

// ---- Tier 1: Semantic Model ----

let semanticModel (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let key (n: SemanticName) = n.Key
    render (
        header digest "Tier 1 (Semantic Model): what can be true"
        @ [ "namespace " + rootNamespace w; "" ]
        @ union (sprintf "The states of the %s workflow; the initial state is listed first." w.Key) (stateType w) (s.States |> List.map key)
        @ union (sprintf "The commands the %s workflow accepts." w.Key) (commandType w) (s.Commands |> List.map key)
        @ (if List.isEmpty s.Guards then []
           else union "Named guard predicates. Their bodies are handwritten extension contracts." (guardType w) (s.Guards |> List.map key))
        @ (if List.isEmpty s.Invariants then []
           else union "Named invariants. Their bodies are handwritten extension contracts." (invariantType w) (s.Invariants |> List.map key))
        @ (if List.isEmpty s.Effects then []
           else union "Effects an accepted command requests. Requested as data; only a host performs them." (effectType w) (s.Effects |> List.map key))
        |> fun lines -> List.take (List.length lines - 1) lines)

// ---- Tier 2: Transition ----

let transition (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let st, cmd = stateType w, commandType w
    let pairs = [ for state in s.States do for command in s.Commands -> state, command ]
    let edge (state: SemanticName) (command: SemanticName) =
        s.Workflow.Transitions |> List.tryFind (fun t -> t.From.Key = state.Key && t.Command.Key = command.Key)
    let pattern state command = sprintf "| %s, %s ->" (qualify st state) (qualify cmd command)

    let refusal =
        union "Why a command was not applied. Each case is a distinct remedy." (refusalType w)
            ([ sprintf "InvalidTransition of state: %s * command: %s" st cmd ]
             @ (if s.HasCapabilities then [ sprintf "MissingCapabilities of command: %s * capabilities: string list" cmd ] else [])
             @ (if List.isEmpty s.Guards then [] else [ sprintf "GuardRejected of guard: %s" (guardType w) ])
             @ (if List.isEmpty s.Invariants then [] else [ sprintf "InvariantViolated of invariant: %s" (invariantType w) ]))

    let decision =
        [ "/// An accepted command. Requested effects are data; this tier performs none."
          "type " + decisionType w + " ="
          "    { Previous: " + st
          "      Next: " + st
          (if List.isEmpty s.Effects then "      Command: " + cmd + " }" else "      Command: " + cmd)
          ]
        @ (if List.isEmpty s.Effects then [] else [ "      Effects: " + effectType w + " list }" ])
        @ [ "" ]

    let rules =
        if not s.HasRules then []
        else
            [ "/// Handwritten extension contract. Every guard and invariant must be decided"
              "/// by supplied code; there is no default, so a missing rule does not compile."
              "type " + rulesType w + " =" ]
            @ ((if List.isEmpty s.Guards then [] else [ sprintf "Guard: %s -> %s -> %s -> bool" (guardType w) st cmd ])
               @ (if List.isEmpty s.Invariants then [] else [ sprintf "Invariant: %s -> %s -> bool" (invariantType w) st ])
               |> List.mapi (fun i field -> (if i = 0 then "    { " else "      ") + field)
               |> fun fields -> List.mapi (fun i (f: string) -> if i = List.length fields - 1 then f + " }" else f) fields)
            @ [ "" ]

    let legal =
        [ "/// Every legal transition as (from, command, to)."
          sprintf "let legal : (%s * %s * %s) list =" st cmd st ]
        @ (s.Workflow.Transitions
           |> List.mapi (fun i t ->
               (if i = 0 then "    [ " else "      ")
               + sprintf "%s, %s, %s" (qualify st t.From) (qualify cmd t.Command) (qualify st t.To))
           |> fun rows -> List.mapi (fun i (r: string) -> if i = List.length rows - 1 then r + " ]" else r) rows)
        @ [ "" ]

    let target =
        [ "/// The target of a command, or None where the command is not legal. Every"
          "/// (state, command) pair is listed; there is no catch-all."
          sprintf "let target (state: %s) (command: %s) : %s option =" st cmd st
          "    match state, command with" ]
        @ (pairs |> List.map (fun (state, command) ->
               "    " + pattern state command + " " + (match edge state command with Some t -> "Some " + qualify st t.To | None -> "None")))
        @ [ "" ]

    let guards =
        if List.isEmpty s.Guards then []
        else
            [ "/// The guards a legal command must satisfy in a state."
              sprintf "let guards (state: %s) (command: %s) : %s list =" st cmd (guardType w)
              "    match state, command with" ]
            @ (pairs |> List.map (fun (state, command) ->
                   let names = edge state command |> Option.map (fun t -> t.Guards |> List.map (fun g -> qualify (guardType w) g.Name)) |> Option.defaultValue []
                   "    " + pattern state command + " " + list names))
            @ [ "" ]

    let invariants =
        if List.isEmpty s.Invariants then []
        else
            [ "/// The invariants that must hold in a state."
              sprintf "let invariantsIn (state: %s) : %s list =" st (invariantType w)
              "    match state with" ]
            @ (s.States |> List.map (fun state ->
                   let names =
                       s.Workflow.Invariants
                       |> List.filter (fun i -> i.HoldsIn |> List.exists (fun h -> h.Key = state.Key))
                       |> List.map (fun i -> qualify (invariantType w) i.Name)
                   sprintf "    | %s -> %s" (qualify st state) (list names)))
            @ [ "" ]

    let capabilities =
        if not s.HasCapabilities then []
        else
            [ "/// Semantic capabilities a command requires. Checked against the held set the"
              "/// host supplies; this is semantic authority, not authentication."
              sprintf "let requiredCapabilities (command: %s) : string list =" cmd
              "    match command with" ]
            @ (s.Commands |> List.map (fun command ->
                   let ids =
                       s.Workflow.Capabilities
                       |> List.filter (fun c -> c.Command.Key = command.Key)
                       |> List.map (fun c -> literal (Ordo.Core.Identifiers.CapabilityId.value c.Capability))
                   sprintf "    | %s -> %s" (qualify cmd command) (list ids)))
            @ [ "" ]

    let effects =
        if List.isEmpty s.Effects then []
        else
            [ "/// Effects an accepted command requests."
              sprintf "let effects (command: %s) : %s list =" cmd (effectType w)
              "    match command with" ]
            @ (s.Commands |> List.map (fun command ->
                   let requested = s.Effects |> List.filter (fun e -> e.Key = command.Key) |> List.map (qualify (effectType w))
                   sprintf "    | %s -> %s" (qualify cmd command) (list requested)))
            @ [ "" ]

    let rf = refusalType w
    let parameters =
        (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else [])
        @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
        @ [ sprintf "(state: %s)" st; sprintf "(command: %s)" cmd ]
    let construct =
        if List.isEmpty s.Effects then "{ Previous = state; Next = next; Command = command }"
        else "{ Previous = state; Next = next; Command = command; Effects = effects command }"
    let checks =
        (if not s.HasCapabilities then []
         else
             [ "|> Result.bind (fun next ->"
               "    match requiredCapabilities command |> List.filter (fun required -> not (Set.contains required held)) with"
               "    | [] -> Ok next"
               sprintf "    | missing -> Error(%s.MissingCapabilities(command, missing)))" rf ])
        @ (if List.isEmpty s.Guards then []
           else
               [ "|> Result.bind (fun next ->"
                 "    match guards state command |> List.tryFind (fun guard -> not (rules.Guard guard state command)) with"
                 sprintf "    | Some guard -> Error(%s.GuardRejected guard)" rf
                 "    | None -> Ok next)" ])
        @ (if List.isEmpty s.Invariants then []
           else
               [ "|> Result.bind (fun next ->"
                 "    match invariantsIn next |> List.tryFind (fun invariant -> not (rules.Invariant invariant next)) with"
                 sprintf "    | Some invariant -> Error(%s.InvariantViolated invariant)" rf
                 "    | None -> Ok next)" ])
    let accepted =
        if List.isEmpty checks then [ "    | Some next -> Ok " + construct ]
        else [ "    | Some next ->"; "        Ok next" ] @ indent 8 (checks @ [ "|> Result.map (fun next -> " + construct + ")" ])
    let decide =
        [ "/// Decides one command. Refusal is data; nothing is applied or performed here."
          sprintf "let decide %s : Result<%s, %s> =" (String.concat " " parameters) (decisionType w) rf
          "    match target state command with"
          sprintf "    | None -> Error(%s.InvalidTransition(state, command))" rf ]
        @ accepted

    render (
        header digest "Tier 2 (Transition): what legal change may happen"
        @ [ "namespace " + rootNamespace w; "" ]
        @ refusal @ decision @ rules
        @ [ "/// The legal transitions, decided from one plan. Depends only on Tier 1."
            "[<RequireQualifiedAccess>]"
            "module " + transitionModule w + " =" ]
        @ indent 4 ([ "" ] @ legal @ target @ guards @ invariants @ capabilities @ effects @ decide))

// ---- Tier 3: Orchestration ----

let orchestration (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let st, cmd, dt = stateType w, commandType w, decisionType w
    let instant = "global.System.DateTimeOffset"
    let outcome =
        if List.isEmpty s.Effects then []
        else
            union "What the host reports about a requested effect. Unknown is a first-class outcome, not an error to swallow." (effectOutcomeType w)
                [ "Completed"; "Failed of reason: string"; "Unknown of reason: string" ]
    let ports =
        [ "/// Ports this workflow requires. Implemented by a host (Tier 4); generated code never implements them."
          "type " + portsType w + " =" ]
        @ (if s.HasClock then [ sprintf "    abstract CurrentTime: unit -> %s" instant ] else [])
        @ (if List.isEmpty s.Effects then [] else [ sprintf "    abstract Perform: effect: %s * decision: %s -> %s" (effectType w) dt (effectOutcomeType w) ])
        @ [ "" ]
    let at = if s.HasClock then sprintf " * at: %s" instant else ""
    let reported = if List.isEmpty s.Effects then "" else sprintf " * effects: (%s * %s) list" (effectType w) (effectOutcomeType w)
    let result =
        union "The result of handling one command. It reports effect outcomes; it does not decide what a failed or unknown effect means for the workflow." (resultType w)
            [ sprintf "Accepted of decision: %s%s%s" dt at reported; sprintf "Refused of refusal: %s%s" (refusalType w) at ]
    let parameters =
        [ sprintf "(ports: %s)" (portsType w) ]
        @ (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else [])
        @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
        @ [ sprintf "(state: %s)" st; sprintf "(command: %s)" cmd ]
    let arguments =
        (if s.HasRules then [ "rules" ] else []) @ (if s.HasCapabilities then [ "held" ] else []) @ [ "state"; "command" ]
    let atArg = if s.HasClock then ", at" else ""
    let performed = if List.isEmpty s.Effects then "" else ", decision.Effects |> List.map (fun effect -> effect, ports.Perform(effect, decision))"
    let handle =
        [ "/// Coordinates one command: reads ports, delegates the decision to Tier 2 and"
          "/// asks the host to perform requested effects. It makes no semantic decision."
          sprintf "let handle %s : %s =" (String.concat " " parameters) (resultType w) ]
        @ (if s.HasClock then [ "    let at = ports.CurrentTime()" ] else [])
        @ [ sprintf "    match %s.decide %s with" (transitionModule w) (String.concat " " arguments)
            sprintf "    | Error refusal -> %s.Refused(refusal%s)" (resultType w) atArg
            sprintf "    | Ok decision -> %s.Accepted(decision%s%s)" (resultType w) atArg performed ]
    render (
        header digest "Tier 3 (Orchestration): coordinates ports and decisions"
        @ [ "namespace " + rootNamespace w; "" ]
        @ outcome @ ports @ result
        @ [ "/// Coordinates the workflow. Depends on Tiers 1 and 2 only."
            "[<RequireQualifiedAccess>]"
            "module " + orchestrationModule w + " =" ]
        @ indent 4 ([ "" ] @ handle))
