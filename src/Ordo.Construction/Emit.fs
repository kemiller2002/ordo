/// F# source emission for one finite-state workflow. Every token that reaches
/// the output is either fixed text written here, a grammar-checked semantic
/// name, a grammar-checked capability identifier, or the hex plan digest.
/// No requirement text, question, trace key or other plan prose is ever
/// rendered into code.
module internal Ordo.Construction.Emit

open Ordo.Core.ConstructionPlan
open Ordo.Construction.Naming

/// LF line endings and a single trailing newline, whatever the platform.
let private render (lines: string list) = String.concat "\n" lines + "\n"

let private indent n (lines: string list) =
    lines |> List.map (fun line -> if line = "" then "" else String.replicate n " " + line)

let private header (generator: string) (digest: string) (tier: string) =
    [ sprintf "// <auto-generated by %s from %s>" generator digest
      sprintf "// %s. Regenerated from the construction plan; edits are overwritten." tier
      "// Handwritten behavior belongs in extension code, never in this file."
      "" ]

/// A capability literal. The plan grammar already restricts capability text
/// to ASCII words joined by . : - _; this re-check keeps the emitter safe on
/// its own terms rather than trusting the caller.
let private literal (text: string) =
    if text |> Seq.forall (fun ch -> System.Char.IsAsciiLetterOrDigit ch || ch = '.' || ch = ':' || ch = '-' || ch = '_') then
        "\"" + text + "\""
    else invalidArg "text" "capability text outside the emitter grammar"

let private union (doc: string) (name: string) (cases: string list) =
    [ "/// " + doc
      "[<RequireQualifiedAccess>]"
      "type " + name + " =" ]
    @ (cases |> List.map (fun case -> "    | " + case))
    @ [ "" ]

let private qualify typeName (name: SemanticName) = typeName + "." + name.Key

/// What the workflow needs, decided once from the plan.
type Shape =
    { /// `ordo.construction/1` for vocabulary 1 plans, `ordo.construction/2`
      /// for vocabulary 2 plans.
      Generator: string
      Workflow: Workflow
      States: SemanticName list
      Commands: SemanticName list
      Guards: SemanticName list
      Invariants: SemanticName list
      Effects: SemanticName list
      /// Each effect's declared failure disposition (vocabulary 2 only).
      Dispositions: (SemanticName * EffectFailureDisposition) list
      /// Vocabulary 5: each effect's outcome policy, in effect order.
      Policies: EffectPolicy list
      HasClock: bool
      HasCapabilities: bool
      /// Vocabulary 3: pairs the plan leaves undecided, explicitly or by an
      /// `undecided` pair rule. Empty for earlier vocabularies.
      Undecided: (SemanticName * SemanticName) list
      /// Vocabulary 4: typed refusal codes, sorted. Empty for earlier vocabularies.
      Codes: SemanticName list
      /// Vocabulary 4: branching transitions as (from, command, targets).
      Branching: (SemanticName * SemanticName * SemanticName list) list }

    member this.HasRules = not (List.isEmpty this.Guards && List.isEmpty this.Invariants && List.isEmpty this.Branching)
    member this.HasPorts = this.HasClock || not (List.isEmpty this.Effects)

/// The pairs a vocabulary 3 plan leaves open: explicit undecided
/// declarations, and every unlisted pair outside a terminal state when the
/// pair rule says unlisted pairs are undecided.
let undecidedPairs (w: Workflow) =
    let named (state: SemanticName) (command: SemanticName) =
        (w.Transitions |> List.exists (fun t -> t.From.Key = state.Key && t.Command.Key = command.Key))
        || (w.BranchingTransitions |> List.exists (fun b -> b.InState.Key = state.Key && b.OnCommand.Key = command.Key))
        || (w.Refusals |> List.exists (fun r -> r.InState.Key = state.Key && r.OnCommand.Key = command.Key))
    [ for state in w.States do
          for command in w.Commands do
              let explicit = w.UndecidedTransitions |> List.exists (fun u -> u.InState.Key = state.Name.Key && u.OnCommand.Key = command.Key)
              let byRule =
                  match w.PairRule with
                  | Some(UnlistedPairs.Undecided, _) -> state.Role <> Terminal && not (named state.Name command)
                  | Some(UnlistedPairs.Refused, _) | None -> false
              if explicit || byRule then state.Name, command ]

let shapeOf (generator: string) (w: Workflow) =
    { Generator = generator
      Workflow = w
      States = w.States |> List.map _.Name
      Commands = w.Commands
      Guards = w.Transitions |> List.collect (fun t -> t.Guards |> List.map _.Name) |> List.distinctBy _.Key |> List.sortBy _.Key
      Invariants = w.Invariants |> List.map _.Name
      Effects = w.Ports |> List.choose (fun p -> match p.Kind with TransitionEffectPort(c, _) -> Some c | CurrentTimePort -> None)
      Dispositions =
        w.Ports
        |> List.choose (fun p ->
            match p.Kind with
            | TransitionEffectPort(c, Some disposition) -> Some(c, disposition)
            | TransitionEffectPort(_, None) | CurrentTimePort -> None)
      HasClock = w.Ports |> List.exists (fun p -> p.Kind = CurrentTimePort)
      HasCapabilities = not (List.isEmpty w.Capabilities)
      Undecided = undecidedPairs w
      Policies = w.EffectPolicies
      Codes = w.RefusalCodes |> List.map fst
      Branching = w.BranchingTransitions |> List.map (fun b -> b.InState, b.OnCommand, b.Targets) }

let private list (items: string list) =
    match items with
    | [] -> "[]"
    | _ -> "[ " + String.concat "; " items + " ]"

// ---- Tier 1: Semantic Model ----

let semanticModel (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let key (n: SemanticName) = n.Key
    render (
        header s.Generator digest "Tier 1 (Semantic Model): what can be true"
        @ [ "namespace " + rootNamespace w; "" ]
        @ union (sprintf "The states of the %s workflow; the initial state is listed first." w.Key) (stateType w) (s.States |> List.map key)
        @ union (sprintf "The commands the %s workflow accepts." w.Key) (commandType w) (s.Commands |> List.map key)
        @ (if List.isEmpty s.Guards then []
           else union "Named guard predicates. Their bodies are handwritten extension contracts." (guardType w) (s.Guards |> List.map key))
        @ (if List.isEmpty s.Invariants then []
           else union "Named invariants. Their bodies are handwritten extension contracts." (invariantType w) (s.Invariants |> List.map key))
        @ (if List.isEmpty s.Effects then []
           else union "Effects an accepted command requests. Requested as data; only a host performs them." (effectType w) (s.Effects |> List.map key))
        @ (if List.isEmpty s.Codes then []
           else union "Typed refusal codes. Each names one documented reason a command is refused." (refusalCodeType w) (s.Codes |> List.map key))
        @ (s.Branching
           |> List.collect (fun (from, command, targets) ->
               union (sprintf "The states command %s may lead to from %s. A handwritten selector picks one." command.Key from.Key)
                   (branchType w from command) (targets |> List.map key)))
        |> fun lines -> List.take (List.length lines - 1) lines)

// ---- Tier 2: Transition ----

let transition (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let st, cmd = stateType w, commandType w
    let pairs = [ for state in s.States do for command in s.Commands -> state, command ]
    let edge (state: SemanticName) (command: SemanticName) =
        s.Workflow.Transitions |> List.tryFind (fun t -> t.From.Key = state.Key && t.Command.Key = command.Key)
    let pattern state command = sprintf "| %s, %s ->" (qualify st state) (qualify cmd command)

    let refusal =
        union "Why a command was not applied. Each case is a distinct remedy." (refusalType w)
            ([ sprintf "InvalidTransition of state: %s * command: %s" st cmd ]
             @ (if List.isEmpty s.Undecided then [] else [ sprintf "Undecided of state: %s * command: %s" st cmd ])
             @ (if s.HasCapabilities then [ sprintf "MissingCapabilities of command: %s * capabilities: string list" cmd ] else [])
             @ (if List.isEmpty s.Guards then [] else [ sprintf "GuardRejected of guard: %s" (guardType w) ])
             @ (if List.isEmpty s.Invariants then [] else [ sprintf "InvariantViolated of invariant: %s" (invariantType w) ]))

    let decision =
        [ "/// An accepted command. Requested effects are data; this tier performs none."
          "type " + decisionType w + " ="
          "    { Previous: " + st
          "      Next: " + st
          (if List.isEmpty s.Effects then "      Command: " + cmd + " }" else "      Command: " + cmd)
          ]
        @ (if List.isEmpty s.Effects then [] else [ "      Effects: " + effectType w + " list }" ])
        @ [ "" ]

    let rules =
        if not s.HasRules then []
        else
            (if List.isEmpty s.Branching then
                 [ "/// Handwritten extension contract. Every guard and invariant must be decided"
                   "/// by supplied code; there is no default, so a missing rule does not compile." ]
             else
                 [ "/// Handwritten extension contract. Every guard, invariant and branching selector must be"
                   "/// decided by supplied code; there is no default, so a missing rule does not compile. A"
                   "/// selector returns a closed union of its transition's targets, so it cannot pick another state." ])
            @ [ "type " + rulesType w + " =" ]
            @ ((if List.isEmpty s.Guards then [] else [ sprintf "Guard: %s -> %s -> %s -> bool" (guardType w) st cmd ])
               @ (if List.isEmpty s.Invariants then [] else [ sprintf "Invariant: %s -> %s -> bool" (invariantType w) st ])
               @ (s.Branching |> List.map (fun (from, command, _) -> sprintf "%s: unit -> %s" (selectorField from command) (branchType w from command)))
               |> List.mapi (fun i field -> (if i = 0 then "    { " else "      ") + field)
               |> fun fields -> List.mapi (fun i (f: string) -> if i = List.length fields - 1 then f + " }" else f) fields)
            @ [ "" ]

    let legal =
        [ (if List.isEmpty s.Branching then "/// Every legal transition as (from, command, to)."
           else "/// Every legal single-target transition as (from, command, to). Branching ones are in `branching`.")
          sprintf "let legal : (%s * %s * %s) list =" st cmd st ]
        @ (s.Workflow.Transitions
           |> List.mapi (fun i t ->
               (if i = 0 then "    [ " else "      ")
               + sprintf "%s, %s, %s" (qualify st t.From) (qualify cmd t.Command) (qualify st t.To))
           |> fun rows -> List.mapi (fun i (r: string) -> if i = List.length rows - 1 then r + " ]" else r) rows)
        @ [ "" ]

    let branching =
        if List.isEmpty s.Branching then []
        else
            [ "/// Every branching transition as (from, command, the targets its selector may pick)."
              sprintf "let branching : (%s * %s * %s list) list =" st cmd st ]
            @ (s.Branching
               |> List.mapi (fun i (from, command, targets) ->
                   (if i = 0 then "    [ " else "      ")
                   + sprintf "%s, %s, %s" (qualify st from) (qualify cmd command) (list (targets |> List.map (qualify st))))
               |> fun rows -> List.mapi (fun i (r: string) -> if i = List.length rows - 1 then r + " ]" else r) rows)
            @ [ "" ]

    let branchOf (state: SemanticName) (command: SemanticName) =
        s.Branching |> List.tryFind (fun (from, c, _) -> from.Key = state.Key && c.Key = command.Key)

    // The selector's union is closed over the plan's targets, so a selector
    // cannot pick a state the plan does not allow.
    let next =
        if List.isEmpty s.Branching then []
        else
            [ "/// The target of a command: fixed for a single-target transition, picked by the handwritten"
              "/// selector for a branching one, None where the command is not legal. Every pair is listed;"
              "/// there is no catch-all."
              sprintf "let next (rules: %s) (state: %s) (command: %s) : %s option =" (rulesType w) st cmd st
              "    match state, command with" ]
            @ (pairs |> List.map (fun (state, command) ->
                   match branchOf state command with
                   | Some(from, c, targets) ->
                       let bt = branchType w from c
                       let arms = targets |> List.map (fun t -> sprintf "%s -> %s" (qualify bt t) (qualify st t)) |> String.concat " | "
                       sprintf "    %s Some(match rules.%s () with %s)" (pattern state command) (selectorField from c) arms
                   | None -> sprintf "    %s target state command" (pattern state command)))
            @ [ "" ]

    let target =
        (if List.isEmpty s.Branching then
             [ "/// The target of a command, or None where the command is not legal. Every"
               "/// (state, command) pair is listed; there is no catch-all." ]
         else
             [ "/// The fixed target of a single-target transition, or None where the plan lists none; a"
               "/// branching transition's target is picked in `next`. Every (state, command) pair is listed;"
               "/// there is no catch-all." ])
        @ [ sprintf "let target (state: %s) (command: %s) : %s option =" st cmd st
            "    match state, command with" ]
        @ (pairs |> List.map (fun (state, command) ->
               "    " + pattern state command + " " + (match edge state command with Some t -> "Some " + qualify st t.To | None -> "None")))
        @ [ "" ]

    let undecided =
        if List.isEmpty s.Undecided then []
        else
            let isOpen (state: SemanticName) (command: SemanticName) =
                s.Undecided |> List.exists (fun (u, c) -> u.Key = state.Key && c.Key = command.Key)
            [ "/// Pairs the requirements leave undecided. They are open obligations, not"
              "/// refusals: `decide` reports them as Undecided so no caller mistakes them"
              "/// for a decided refusal. Every pair is listed; there is no catch-all."
              sprintf "let undecided (state: %s) (command: %s) : bool =" st cmd
              "    match state, command with" ]
            @ (pairs |> List.map (fun (state, command) ->
                   "    " + pattern state command + " " + (if isOpen state command then "true" else "false")))
            @ [ "" ]

    let guards =
        if List.isEmpty s.Guards then []
        else
            [ "/// The guards a legal command must satisfy in a state."
              sprintf "let guards (state: %s) (command: %s) : %s list =" st cmd (guardType w)
              "    match state, command with" ]
            @ (pairs |> List.map (fun (state, command) ->
                   let names = edge state command |> Option.map (fun t -> t.Guards |> List.map (fun g -> qualify (guardType w) g.Name)) |> Option.defaultValue []
                   "    " + pattern state command + " " + list names))
            @ [ "" ]

    let invariants =
        if List.isEmpty s.Invariants then []
        else
            [ "/// The invariants that must hold in a state."
              sprintf "let invariantsIn (state: %s) : %s list =" st (invariantType w)
              "    match state with" ]
            @ (s.States |> List.map (fun state ->
                   let names =
                       s.Workflow.Invariants
                       |> List.filter (fun i -> i.HoldsIn |> List.exists (fun h -> h.Key = state.Key))
                       |> List.map (fun i -> qualify (invariantType w) i.Name)
                   sprintf "    | %s -> %s" (qualify st state) (list names)))
            @ [ "" ]

    let capabilities =
        if not s.HasCapabilities then []
        else
            [ "/// Semantic capabilities a command requires. Checked against the held set the"
              "/// host supplies; this is semantic authority, not authentication."
              sprintf "let requiredCapabilities (command: %s) : string list =" cmd
              "    match command with" ]
            @ (s.Commands |> List.map (fun command ->
                   let ids =
                       s.Workflow.Capabilities
                       |> List.filter (fun c -> c.Command.Key = command.Key)
                       |> List.map (fun c -> literal (Ordo.Core.Identifiers.CapabilityId.value c.Capability))
                   sprintf "    | %s -> %s" (qualify cmd command) (list ids)))
            @ [ "" ]

    let effects =
        if List.isEmpty s.Effects then []
        else
            [ "/// Effects an accepted command requests."
              sprintf "let effects (command: %s) : %s list =" cmd (effectType w)
              "    match command with" ]
            @ (s.Commands |> List.map (fun command ->
                   let requested = s.Effects |> List.filter (fun e -> e.Key = command.Key) |> List.map (qualify (effectType w))
                   sprintf "    | %s -> %s" (qualify cmd command) (list requested)))
            @ [ "" ]

    // Vocabulary 4: which typed code each refusal reports. Pair and guard
    // codes are separate exhaustive functions, so no match arm is shadowed and
    // there is no catch-all.
    let codes =
        if List.isEmpty s.Codes then []
        else
            let rc = refusalCodeType w
            let assigned subject = s.Workflow.CodeAssignments |> List.tryFind (fun a -> a.Target = subject) |> Option.map _.Code
            let named (state: SemanticName) (command: SemanticName) =
                Option.isSome (edge state command) || Option.isSome (branchOf state command)
                || (s.Workflow.Refusals |> List.exists (fun r -> r.InState.Key = state.Key && r.OnCommand.Key = command.Key))
                || (s.Undecided |> List.exists (fun (u, c) -> u.Key = state.Key && c.Key = command.Key))
            let pairCode (state: SemanticName) (command: SemanticName) =
                match assigned (CodeSubject.Pair(state, command)) with
                | Some code -> Some code
                | None when not (named state command) -> assigned CodeSubject.Unlisted
                | None -> None
            let some code = code |> Option.map (fun c -> sprintf "Some %s" (qualify rc c)) |> Option.defaultValue "None"
            let rf = refusalType w
            [ "/// The typed code the plan assigns to a refused pair, or None where it assigns none."
              sprintf "let pairCode (state: %s) (command: %s) : %s option =" st cmd rc
              "    match state, command with" ]
            @ (pairs |> List.map (fun (state, command) -> sprintf "    %s %s" (pattern state command) (some (pairCode state command))))
            @ [ "" ]
            @ (if List.isEmpty s.Guards then []
               else
                   [ "/// The typed code the plan assigns to a rejected guard, or None where it assigns none."
                     sprintf "let guardCode (guard: %s) : %s option =" (guardType w) rc
                     "    match guard with" ]
                   @ (s.Guards |> List.map (fun g -> sprintf "    | %s -> %s" (qualify (guardType w) g) (some (assigned (CodeSubject.Guard g)))))
                   @ [ "" ])
            @ [ "/// The typed code of a refusal, as the plan assigns it; None where the plan assigns none."
                sprintf "let refusalCode (refusal: %s) : %s option =" rf rc
                "    match refusal with"
                sprintf "    | %s.InvalidTransition(state, command) -> pairCode state command" rf ]
            @ (if List.isEmpty s.Undecided then [] else [ sprintf "    | %s.Undecided _ -> None" rf ])
            @ (if s.HasCapabilities then [ sprintf "    | %s.MissingCapabilities _ -> None" rf ] else [])
            @ (if List.isEmpty s.Guards then [] else [ sprintf "    | %s.GuardRejected guard -> guardCode guard" rf ])
            @ (if List.isEmpty s.Invariants then [] else [ sprintf "    | %s.InvariantViolated _ -> None" rf ])

    let rf = refusalType w
    let parameters =
        (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else [])
        @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
        @ [ sprintf "(state: %s)" st; sprintf "(command: %s)" cmd ]
    let construct =
        if List.isEmpty s.Effects then "{ Previous = state; Next = next; Command = command }"
        else "{ Previous = state; Next = next; Command = command; Effects = effects command }"
    let checks =
        (if not s.HasCapabilities then []
         else
             [ "|> Result.bind (fun next ->"
               "    match requiredCapabilities command |> List.filter (fun required -> not (Set.contains required held)) with"
               "    | [] -> Ok next"
               sprintf "    | missing -> Error(%s.MissingCapabilities(command, missing)))" rf ])
        @ (if List.isEmpty s.Guards then []
           else
               [ "|> Result.bind (fun next ->"
                 "    match guards state command |> List.tryFind (fun guard -> not (rules.Guard guard state command)) with"
                 sprintf "    | Some guard -> Error(%s.GuardRejected guard)" rf
                 "    | None -> Ok next)" ])
        @ (if List.isEmpty s.Invariants then []
           else
               [ "|> Result.bind (fun next ->"
                 "    match invariantsIn next |> List.tryFind (fun invariant -> not (rules.Invariant invariant next)) with"
                 sprintf "    | Some invariant -> Error(%s.InvariantViolated invariant)" rf
                 "    | None -> Ok next)" ])
    let accepted =
        if List.isEmpty checks then [ "    | Some next -> Ok " + construct ]
        else [ "    | Some next ->"; "        Ok next" ] @ indent 8 (checks @ [ "|> Result.map (fun next -> " + construct + ")" ])
    let decide =
        [ "/// Decides one command. Refusal is data; nothing is applied or performed here."
          sprintf "let decide %s : Result<%s, %s> =" (String.concat " " parameters) (decisionType w) rf
          (if List.isEmpty s.Branching then "    match target state command with" else "    match next rules state command with") ]
        @ (if List.isEmpty s.Undecided then [] else [ sprintf "    | None when undecided state command -> Error(%s.Undecided(state, command))" rf ])
        @ [ sprintf "    | None -> Error(%s.InvalidTransition(state, command))" rf ]
        @ accepted
        @ (if List.isEmpty codes then [] else [ "" ])

    render (
        header s.Generator digest "Tier 2 (Transition): what legal change may happen"
        @ [ "namespace " + rootNamespace w; "" ]
        @ refusal @ decision @ rules
        @ [ "/// The legal transitions, decided from one plan. Depends only on Tier 1."
            "[<RequireQualifiedAccess>]"
            "module " + transitionModule w + " =" ]
        @ indent 4 ([ "" ] @ legal @ branching @ target @ next @ undecided @ guards @ invariants @ capabilities @ effects @ decide @ codes))

// ---- Tier 3: Orchestration ----

/// Vocabulary 1: reports effect outcomes and leaves their meaning to the
/// host. Kept byte for byte as `ordo.construction/1` emitted it.
let private orchestrationV1 (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let st, cmd, dt = stateType w, commandType w, decisionType w
    let instant = "global.System.DateTimeOffset"
    let outcome =
        if List.isEmpty s.Effects then []
        else
            union "What the host reports about a requested effect. Unknown is a first-class outcome, not an error to swallow." (effectOutcomeType w)
                [ "Completed"; "Failed of reason: string"; "Unknown of reason: string" ]
    let ports =
        [ "/// Ports this workflow requires. Implemented by a host (Tier 4); generated code never implements them."
          "type " + portsType w + " =" ]
        @ (if s.HasClock then [ sprintf "    abstract CurrentTime: unit -> %s" instant ] else [])
        @ (if List.isEmpty s.Effects then [] else [ sprintf "    abstract Perform: effect: %s * decision: %s -> %s" (effectType w) dt (effectOutcomeType w) ])
        @ [ "" ]
    let at = if s.HasClock then sprintf " * at: %s" instant else ""
    let reported = if List.isEmpty s.Effects then "" else sprintf " * effects: (%s * %s) list" (effectType w) (effectOutcomeType w)
    let result =
        union "The result of handling one command. It reports effect outcomes; it does not decide what a failed or unknown effect means for the workflow." (resultType w)
            [ sprintf "Accepted of decision: %s%s%s" dt at reported; sprintf "Refused of refusal: %s%s" (refusalType w) at ]
    let parameters =
        [ sprintf "(ports: %s)" (portsType w) ]
        @ (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else [])
        @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
        @ [ sprintf "(state: %s)" st; sprintf "(command: %s)" cmd ]
    let arguments =
        (if s.HasRules then [ "rules" ] else []) @ (if s.HasCapabilities then [ "held" ] else []) @ [ "state"; "command" ]
    let atArg = if s.HasClock then ", at" else ""
    let performed = if List.isEmpty s.Effects then "" else ", decision.Effects |> List.map (fun effect -> effect, ports.Perform(effect, decision))"
    let handle =
        [ "/// Coordinates one command: reads ports, delegates the decision to Tier 2 and"
          "/// asks the host to perform requested effects. It makes no semantic decision."
          sprintf "let handle %s : %s =" (String.concat " " parameters) (resultType w) ]
        @ (if s.HasClock then [ "    let at = ports.CurrentTime()" ] else [])
        @ [ sprintf "    match %s.decide %s with" (transitionModule w) (String.concat " " arguments)
            sprintf "    | Error refusal -> %s.Refused(refusal%s)" (resultType w) atArg
            sprintf "    | Ok decision -> %s.Accepted(decision%s%s)" (resultType w) atArg performed ]
    render (
        header s.Generator digest "Tier 3 (Orchestration): coordinates ports and decisions"
        @ [ "namespace " + rootNamespace w; "" ]
        @ outcome @ ports @ result
        @ [ "/// Coordinates the workflow. Depends on Tiers 1 and 2 only."
            "[<RequireQualifiedAccess>]"
            "module " + orchestrationModule w + " =" ]
        @ indent 4 ([ "" ] @ handle))


let private dispositionCase disposition =
    match disposition with
    | EffectFailureDisposition.Remain -> "Remain"
    | EffectFailureDisposition.Proceed -> "Proceed"
    | EffectFailureDisposition.Unresolved -> "Unresolved"

/// Vocabulary 2: applies each effect's declared failure disposition, so a
/// host never decides what a failed or unknown effect means, and reports the
/// post-command state in every case that has one.
let private orchestrationV2 (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let st, cmd, dt, ef = stateType w, commandType w, decisionType w, effectType w
    let outcomeT, failureT, dispositionT, resultT = effectOutcomeType w, effectFailureType w, failureDispositionType w, resultType w
    let instant = "global.System.DateTimeOffset"
    let hasEffects = not (List.isEmpty s.Effects)
    let used =
        [ EffectFailureDisposition.Remain; EffectFailureDisposition.Proceed; EffectFailureDisposition.Unresolved ]
        |> List.filter (fun d -> s.Dispositions |> List.exists (fun (_, declared) -> declared = d))
    let outcome =
        if not hasEffects then []
        else
            union "What the host reports about a requested effect. Unknown is a first-class outcome, not an error to swallow." outcomeT
                [ "Completed"; "Failed of reason: string"; "Unknown of reason: string" ]
            @ union "A requested effect that did not complete. Unknown stays distinct from Failed." failureT
                [ sprintf "Failed of effect: %s * reason: string" ef; sprintf "Unknown of effect: %s * reason: string" ef ]
            @ union "What a failed or unknown effect means for the workflow, as the construction plan declares it." dispositionT
                (used |> List.map dispositionCase)
    let ports =
        [ "/// Ports this workflow requires. Implemented by a host (Tier 4); generated code never implements them."
          "type " + portsType w + " =" ]
        @ (if s.HasClock then [ sprintf "    abstract CurrentTime: unit -> %s" instant ] else [])
        @ (if hasEffects then [ sprintf "    abstract Perform: effect: %s * decision: %s -> %s" ef dt outcomeT ] else [])
        @ [ "" ]
    let at = if s.HasClock then sprintf " * at: %s" instant else ""
    let reported = if hasEffects then sprintf " * effects: (%s * %s) list" ef outcomeT else ""
    let failure = sprintf " * failure: %s" failureT
    let caseFor disposition =
        match disposition with
        | EffectFailureDisposition.Remain ->
            [ "/// An effect failed or its outcome is unknown, and the plan says the workflow remains in its"
              "/// source state. Not an acceptance: `state` is the source state."
              sprintf "| Remained of decision: %s%s%s%s * state: %s" dt at reported failure st ]
        | EffectFailureDisposition.Proceed ->
            [ "/// An effect failed or its outcome is unknown, and the plan says the target state stands."
              "/// `state` is the target state; the failure is reported, not hidden."
              sprintf "| Proceeded of decision: %s%s%s%s * state: %s" dt at reported failure st ]
        | EffectFailureDisposition.Unresolved ->
            [ "/// An effect failed or its outcome is unknown, and the plan leaves what that means unresolved."
              "/// No state is chosen here: the host must handle this case explicitly, and the construction"
              "/// records a RESOLVE obligation for it."
              sprintf "| Unresolved of decision: %s%s%s%s" dt at reported failure ]
    let result =
        [ "/// The result of handling one command. Every case that has a post-command state carries it as"
          "/// `state`, so a host never derives it from the decision. What a failed or unknown effect means"
          "/// is decided by the construction plan, not by the host."
          "[<RequireQualifiedAccess>]"
          "type " + resultT + " =" ]
        @ indent 4
            ([ (if hasEffects then "/// Accepted, and every requested effect completed. `state` is the target state."
                else "/// Accepted. `state` is the target state.")
               sprintf "| Accepted of decision: %s%s%s * state: %s" dt at reported st ]
             @ (used |> List.collect caseFor)
             @ [ "/// Refused before any effect was requested. `state` is the unchanged source state."
                 sprintf "| Refused of refusal: %s%s * state: %s" (refusalType w) at st ])
        @ [ "" ]
    let parameters =
        [ sprintf "(ports: %s)" (portsType w) ]
        @ (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else [])
        @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
        @ [ sprintf "(state: %s)" st; sprintf "(command: %s)" cmd ]
    let arguments =
        (if s.HasRules then [ "rules" ] else []) @ (if s.HasCapabilities then [ "held" ] else []) @ [ "state"; "command" ]
    let atArg = if s.HasClock then ", at" else ""
    let onFailure =
        if not hasEffects then []
        else
            [ "/// What a failed or unknown outcome of each effect means, as the plan declares it."
              sprintf "let onFailure (effect: %s) : %s =" ef dispositionT
              "    match effect with" ]
            @ (s.Dispositions |> List.map (fun (effect, d) -> sprintf "    | %s -> %s.%s" (qualify ef effect) dispositionT (dispositionCase d)))
            @ [ ""
                "/// The first requested effect, in request order, that did not complete."
                sprintf "let firstFailure (effects: (%s * %s) list) : %s option =" ef outcomeT failureT
                "    effects"
                "    |> List.tryPick (fun (effect, outcome) ->"
                "        match outcome with"
                sprintf "        | %s.Completed -> None" outcomeT
                sprintf "        | %s.Failed reason -> Some(%s.Failed(effect, reason))" outcomeT failureT
                sprintf "        | %s.Unknown reason -> Some(%s.Unknown(effect, reason)))" outcomeT failureT
                "" ]
    let applied disposition =
        match disposition with
        | EffectFailureDisposition.Remain ->
            sprintf "| %s.Remain -> %s.Remained(decision%s, effects, failure, decision.Previous)" dispositionT resultT atArg
        | EffectFailureDisposition.Proceed ->
            sprintf "| %s.Proceed -> %s.Proceeded(decision%s, effects, failure, decision.Next)" dispositionT resultT atArg
        | EffectFailureDisposition.Unresolved ->
            sprintf "| %s.Unresolved -> %s.Unresolved(decision%s, effects, failure)" dispositionT resultT atArg
    let accepted =
        if not hasEffects then [ sprintf "    | Ok decision -> %s.Accepted(decision%s, decision.Next)" resultT atArg ]
        else
            [ "    | Ok decision ->"
              "        let effects = decision.Effects |> List.map (fun effect -> effect, ports.Perform(effect, decision))"
              "        match firstFailure effects with"
              sprintf "        | None -> %s.Accepted(decision%s, effects, decision.Next)" resultT atArg
              "        | Some failure ->"
              "            match failure with"
              sprintf "            | %s.Failed(effect, _)" failureT
              sprintf "            | %s.Unknown(effect, _) ->" failureT
              "                match onFailure effect with" ]
            @ (used |> List.map (fun d -> "                " + applied d))
    let handle =
        [ "/// Coordinates one command: reads ports, delegates the decision to Tier 2, asks the host to"
          "/// perform requested effects and applies the plan's declared failure disposition. It makes no"
          "/// semantic decision of its own."
          sprintf "let handle %s : %s =" (String.concat " " parameters) resultT ]
        @ (if s.HasClock then [ "    let at = ports.CurrentTime()" ] else [])
        @ [ sprintf "    match %s.decide %s with" (transitionModule w) (String.concat " " arguments)
            sprintf "    | Error refusal -> %s.Refused(refusal%s, state)" resultT atArg ]
        @ accepted
    render (
        header s.Generator digest "Tier 3 (Orchestration): coordinates ports and decisions"
        @ [ "namespace " + rootNamespace w; "" ]
        @ outcome @ ports @ result
        @ [ "/// Coordinates the workflow. Depends on Tiers 1 and 2 only."
            "[<RequireQualifiedAccess>]"
            "module " + orchestrationModule w + " =" ]
        @ indent 4 ([ "" ] @ onFailure @ handle))

let private failedCase action =
    match action with
    | FailedEffectAction.Remain -> "Remain"
    | FailedEffectAction.Proceed -> "Proceed"
    | FailedEffectAction.Compensate -> "Compensate"
    | FailedEffectAction.Escalate -> "Escalate"
    | FailedEffectAction.Unresolved -> "Unresolved"

let private unknownCase action =
    match action with
    | UnknownEffectAction.Reconcile -> "Reconcile"
    | UnknownEffectAction.Escalate -> "Escalate"
    | UnknownEffectAction.Unresolved -> "Unresolved"

/// Vocabulary 5: settles each effect outcome by the plan's policy. A definite
/// failure is retried up to the plan's count; an unknown outcome is never
/// retried, only reconciled by host code or escalated. No state is chosen
/// for an escalated or unresolved outcome.
let private orchestrationV5 (digest: string) (s: Shape) =
    let w = s.Workflow.Name
    let st, cmd, dt, ef = stateType w, commandType w, decisionType w, effectType w
    let outcomeT, failureT, resultT = effectOutcomeType w, effectFailureType w, resultType w
    let failedT, unknownT, reconT = onFailedType w, onUnknownType w, reconciliationType w
    let instant = "global.System.DateTimeOffset"
    let hasEffects = not (List.isEmpty s.Effects)
    let policyOf (effect: SemanticName) = s.Policies |> List.find (fun p -> p.Effect.Key = effect.Key)
    let failedUsed =
        [ FailedEffectAction.Remain; FailedEffectAction.Proceed; FailedEffectAction.Compensate; FailedEffectAction.Escalate; FailedEffectAction.Unresolved ]
        |> List.filter (fun a -> s.Policies |> List.exists (fun p -> p.OnFailed = a))
    let unknownUsed =
        [ UnknownEffectAction.Reconcile; UnknownEffectAction.Escalate; UnknownEffectAction.Unresolved ]
        |> List.filter (fun a -> s.Policies |> List.exists (fun p -> p.OnUnknown = a))
    let reconciles = List.contains UnknownEffectAction.Reconcile unknownUsed
    let compensates = List.contains FailedEffectAction.Compensate failedUsed
    // Compensation that does not complete, and an outcome still unknown after
    // reconciliation, are escalated.
    let escalates =
        compensates || List.contains FailedEffectAction.Escalate failedUsed
        || reconciles || List.contains UnknownEffectAction.Escalate unknownUsed
    let unresolvedUsed = List.contains FailedEffectAction.Unresolved failedUsed || List.contains UnknownEffectAction.Unresolved unknownUsed
    let types =
        if not hasEffects then []
        else
            union "What the host reports about a requested effect. Unknown is a first-class outcome, not an error to swallow." outcomeT
                [ "Completed"; "Failed of reason: string"; "Unknown of reason: string" ]
            @ union "A requested effect that did not complete once the plan's policy was applied. Unknown stays distinct from Failed." failureT
                [ sprintf "Failed of effect: %s * reason: string" ef; sprintf "Unknown of effect: %s * reason: string" ef ]
            @ (if reconciles then
                   union "What host reconciliation found out about an effect whose outcome was unknown." reconT
                       [ "Applied"; "NotApplied of reason: string"; "StillUnknown of reason: string" ]
               else [])
            @ union "What a definitely failed effect means once its retries are spent, as the construction plan declares it." failedT
                (failedUsed |> List.map failedCase)
            @ union "What an effect whose outcome is unknown means, as the construction plan declares it. There is no retry." unknownT
                (unknownUsed |> List.map unknownCase)
    let ports =
        [ "/// Ports this workflow requires. Implemented by a host (Tier 4); generated code never implements them."
          "type " + portsType w + " =" ]
        @ (if s.HasClock then [ sprintf "    abstract CurrentTime: unit -> %s" instant ] else [])
        @ (if hasEffects then [ sprintf "    abstract Perform: effect: %s * decision: %s -> %s" ef dt outcomeT ] else [])
        @ (if reconciles then [ sprintf "    abstract Reconcile: effect: %s * decision: %s -> %s" ef dt reconT ] else [])
        @ (if compensates then [ sprintf "    abstract Compensate: effect: %s * decision: %s -> %s" ef dt outcomeT ] else [])
        @ [ "" ]
    let at = if s.HasClock then sprintf " * at: %s" instant else ""
    let reported = if hasEffects then sprintf " * effects: (%s * %s) list" ef outcomeT else ""
    let failure = sprintf " * failure: %s" failureT
    let result =
        [ "/// The result of handling one command. Every case that has a post-command state carries it as"
          "/// `state`. Escalated and unresolved outcomes carry none: generated code chooses no state for them."
          "[<RequireQualifiedAccess>]"
          "type " + resultT + " =" ]
        @ indent 4
            ([ (if hasEffects then "/// Accepted, and every requested effect completed. `state` is the target state."
                else "/// Accepted. `state` is the target state.")
               sprintf "| Accepted of decision: %s%s%s * state: %s" dt at reported st ]
             @ (if List.contains FailedEffectAction.Remain failedUsed then
                    [ "/// An effect definitely failed and the plan says the workflow remains in its source state."
                      sprintf "| Remained of decision: %s%s%s%s * state: %s" dt at reported failure st ]
                else [])
             @ (if List.contains FailedEffectAction.Proceed failedUsed then
                    [ "/// An effect definitely failed and the plan says the target state stands. The failure is reported."
                      sprintf "| Proceeded of decision: %s%s%s%s * state: %s" dt at reported failure st ]
                else [])
             @ (if compensates then
                    [ "/// An effect definitely failed and host compensation completed. `state` is the source state."
                      sprintf "| Compensated of decision: %s%s%s%s * state: %s" dt at reported failure st ]
                else [])
             @ (if escalates then
                    [ "/// A person must decide: the plan escalates this outcome, or compensation or reconciliation"
                      "/// did not settle it. No state is chosen."
                      sprintf "| Escalated of decision: %s%s%s%s" dt at reported failure ]
                else [])
             @ (if unresolvedUsed then
                    [ "/// The plan leaves what this outcome means unresolved. No state is chosen; a RESOLVE obligation"
                      "/// records the open question."
                      sprintf "| Unresolved of decision: %s%s%s%s" dt at reported failure ]
                else [])
             @ [ "/// Refused before any effect was requested. `state` is the unchanged source state."
                 sprintf "| Refused of refusal: %s%s * state: %s" (refusalType w) at st ])
        @ [ "" ]
    let atParam = if s.HasClock then sprintf " (at: %s)" instant else ""
    let atArg = if s.HasClock then ", at" else ""
    let atCall = if s.HasClock then " at" else ""
    let perEffect name typeName (render: EffectPolicy -> string) doc =
        [ doc
          sprintf "let %s (effect: %s) : %s =" name ef typeName
          "    match effect with" ]
        @ (s.Effects |> List.map (fun e -> sprintf "    | %s -> %s" (qualify ef e) (render (policyOf e))))
        @ [ "" ]
    let policy =
        if not hasEffects then []
        else
            perEffect "retries" "int" (fun p -> string p.Retries)
                "/// How many more times a definitely failed effect is performed, as the plan declares it."
            @ perEffect "onFailed" failedT (fun p -> failedT + "." + failedCase p.OnFailed)
                "/// What a definitely failed effect means once its retries are spent."
            @ perEffect "onUnknown" unknownT (fun p -> unknownT + "." + unknownCase p.OnUnknown)
                "/// What an effect whose outcome is unknown means. Never a retry."
    let pp = sprintf "(ports: %s)" (portsType w)
    let settle =
        if not hasEffects then []
        else
            [ "/// Settles one effect outcome by the plan's policy. A definite failure is performed again while"
              "/// retries remain; an unknown outcome is never performed again."
              sprintf "let rec settle %s (decision: %s) (effect: %s) (retriesLeft: int) (outcome: %s) : %s =" pp dt ef outcomeT outcomeT
              "    match outcome with"
              sprintf "    | %s.Completed -> %s.Completed" outcomeT outcomeT
              sprintf "    | %s.Failed _ when retriesLeft > 0 -> settle ports decision effect (retriesLeft - 1) (ports.Perform(effect, decision))" outcomeT
              sprintf "    | %s.Failed reason -> %s.Failed reason" outcomeT outcomeT
              (if reconciles then sprintf "    | %s.Unknown reason -> settleUnknown ports decision effect retriesLeft reason" outcomeT
               else sprintf "    | %s.Unknown reason -> %s.Unknown reason" outcomeT outcomeT) ]
            @ (if not reconciles then []
               else
                   [ ""
                     "/// An unknown outcome is reconciled when the plan says so. Applied counts as completed; not"
                     "/// applied is a definite failure, with whatever retries remain; still unknown stays unknown."
                     sprintf "and settleUnknown %s (decision: %s) (effect: %s) (retriesLeft: int) (reason: string) : %s =" pp dt ef outcomeT
                     "    match onUnknown effect with"
                     sprintf "    | %s.Reconcile -> reconciled ports decision effect retriesLeft (ports.Reconcile(effect, decision))" unknownT ]
                   @ (unknownUsed
                      |> List.filter (fun a -> a <> UnknownEffectAction.Reconcile)
                      |> List.map (fun a -> sprintf "    | %s.%s -> %s.Unknown reason" unknownT (unknownCase a) outcomeT))
                   @ [ ""
                       sprintf "and reconciled %s (decision: %s) (effect: %s) (retriesLeft: int) (found: %s) : %s =" pp dt ef reconT outcomeT
                       "    match found with"
                       sprintf "    | %s.Applied -> %s.Completed" reconT outcomeT
                       sprintf "    | %s.NotApplied reason -> settle ports decision effect retriesLeft (%s.Failed reason)" reconT outcomeT
                       sprintf "    | %s.StillUnknown reason -> %s.Unknown reason" reconT outcomeT ])
            @ [ ""
                "/// The first requested effect, in request order, that did not complete once settled."
                sprintf "let firstFailure (effects: (%s * %s) list) : %s option =" ef outcomeT failureT
                "    effects"
                "    |> List.tryPick (fun (effect, outcome) ->"
                "        match outcome with"
                sprintf "        | %s.Completed -> None" outcomeT
                sprintf "        | %s.Failed reason -> Some(%s.Failed(effect, reason))" outcomeT failureT
                sprintf "        | %s.Unknown reason -> Some(%s.Unknown(effect, reason)))" outcomeT failureT
                "" ]
    let failedArm action =
        match action with
        | FailedEffectAction.Remain -> sprintf "    | %s.Remain -> %s.Remained(decision%s, effects, failure, decision.Previous)" failedT resultT atArg
        | FailedEffectAction.Proceed -> sprintf "    | %s.Proceed -> %s.Proceeded(decision%s, effects, failure, decision.Next)" failedT resultT atArg
        | FailedEffectAction.Compensate -> sprintf "    | %s.Compensate -> compensated ports decision%s effects failure effect" failedT atCall
        | FailedEffectAction.Escalate -> sprintf "    | %s.Escalate -> %s.Escalated(decision%s, effects, failure)" failedT resultT atArg
        | FailedEffectAction.Unresolved -> sprintf "    | %s.Unresolved -> %s.Unresolved(decision%s, effects, failure)" failedT resultT atArg
    let unknownArm action =
        match action with
        | UnknownEffectAction.Reconcile | UnknownEffectAction.Escalate ->
            sprintf "    | %s.%s -> %s.Escalated(decision%s, effects, failure)" unknownT (unknownCase action) resultT atArg
        | UnknownEffectAction.Unresolved -> sprintf "    | %s.Unresolved -> %s.Unresolved(decision%s, effects, failure)" unknownT resultT atArg
    let outcomes =
        if not hasEffects then []
        else
            (if not compensates then []
             else
                 [ "/// Host compensation of a definitely failed effect. Compensation that does not complete is escalated."
                   sprintf "let compensated %s (decision: %s)%s (effects: (%s * %s) list) (failure: %s) (effect: %s) : %s =" pp dt atParam ef outcomeT failureT ef resultT
                   "    match ports.Compensate(effect, decision) with"
                   sprintf "    | %s.Completed -> %s.Compensated(decision%s, effects, failure, decision.Previous)" outcomeT resultT atArg
                   sprintf "    | %s.Failed _ | %s.Unknown _ -> %s.Escalated(decision%s, effects, failure)" outcomeT outcomeT resultT atArg
                   "" ])
            @ [ "/// What a definitely failed effect means for the workflow, by the plan's policy."
                sprintf "let whenFailed %s (decision: %s)%s (effects: (%s * %s) list) (failure: %s) (effect: %s) : %s =" pp dt atParam ef outcomeT failureT ef resultT
                "    match onFailed effect with" ]
            @ (failedUsed |> List.map failedArm)
            @ [ ""
                "/// What an effect still unknown once settled means for the workflow: never a state."
                sprintf "let whenUnknown (decision: %s)%s (effects: (%s * %s) list) (failure: %s) (effect: %s) : %s =" dt atParam ef outcomeT failureT ef resultT
                "    match onUnknown effect with" ]
            @ (unknownUsed |> List.map unknownArm)
            @ [ "" ]
    let parameters =
        [ pp ]
        @ (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else [])
        @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
        @ [ sprintf "(state: %s)" st; sprintf "(command: %s)" cmd ]
    let arguments =
        (if s.HasRules then [ "rules" ] else []) @ (if s.HasCapabilities then [ "held" ] else []) @ [ "state"; "command" ]
    let accepted =
        if not hasEffects then [ sprintf "    | Ok decision -> %s.Accepted(decision%s, decision.Next)" resultT atArg ]
        else
            [ "    | Ok decision ->"
              "        let effects ="
              "            decision.Effects"
              "            |> List.map (fun effect -> effect, settle ports decision effect (retries effect) (ports.Perform(effect, decision)))"
              "        match firstFailure effects with"
              sprintf "        | None -> %s.Accepted(decision%s, effects, decision.Next)" resultT atArg
              sprintf "        | Some(%s.Failed(effect, _) as failure) -> whenFailed ports decision%s effects failure effect" failureT atCall
              sprintf "        | Some(%s.Unknown(effect, _) as failure) -> whenUnknown decision%s effects failure effect" failureT atCall ]
    let handle =
        [ "/// Coordinates one command: reads ports, delegates the decision to Tier 2, asks the host to"
          "/// perform requested effects and applies the plan's outcome policy. It makes no semantic"
          "/// decision of its own."
          sprintf "let handle %s : %s =" (String.concat " " parameters) resultT ]
        @ (if s.HasClock then [ "    let at = ports.CurrentTime()" ] else [])
        @ [ sprintf "    match %s.decide %s with" (transitionModule w) (String.concat " " arguments)
            sprintf "    | Error refusal -> %s.Refused(refusal%s, state)" resultT atArg ]
        @ accepted
    render (
        header s.Generator digest "Tier 3 (Orchestration): coordinates ports and decisions"
        @ [ "namespace " + rootNamespace w; "" ]
        @ types @ ports @ result
        @ [ "/// Coordinates the workflow. Depends on Tiers 1 and 2 only."
            "[<RequireQualifiedAccess>]"
            "module " + orchestrationModule w + " =" ]
        @ indent 4 ([ "" ] @ policy @ settle @ outcomes @ handle))

let orchestration (digest: string) (s: Shape) =
    if s.Generator = Ordo.Construction.Artifacts.GeneratorVersion then orchestrationV1 digest s
    elif s.Generator = Ordo.Construction.Artifacts.GeneratorVersion5 || s.Generator = Ordo.Construction.Artifacts.GeneratorVersion6
         || s.Generator = Ordo.Construction.Artifacts.GeneratorVersion7 then
        orchestrationV5 digest s
    else orchestrationV2 digest s

// ---- Tier 3: Persistence (vocabulary 6) ----

/// Load, deduplicate, decide and save one persisted instance. The save is a
/// compare-and-swap on the revision the decision was made against. An
/// unknown save is settled by reading the instance back (durable scope) or
/// escalated (session scope); it is never assumed to have failed and never
/// written again. Depends on Tiers 1 and 2 only.
let persistence (digest: string) (s: Shape) (p: Persistence) =
    let w = s.Workflow.Name
    let st, cmd, dt, rf = stateType w, commandType w, decisionType w, refusalType w
    let idT, opT, recT, loadT, saveT, exT, storeT = idType w, operationIdType w, recordType w, loadedType w, savedType w, executionType w, storeType w
    let durable = p.Idempotency = IdempotencyScope.Durable
    let session = p.Idempotency = IdempotencyScope.Session
    let unresolvedScope = p.Idempotency = IdempotencyScope.Unresolved
    let staleCase =
        match p.OnStale with
        | StaleAction.Refuse -> sprintf "%s.StaleRevision(decision, expected, current)" exT
        | StaleAction.Escalate -> sprintf "%s.Escalated(decision, sprintf \"revision %%d is stale; the stored revision is %%d\" expected current)" exT
        | StaleAction.Unresolved -> sprintf "%s.Unresolved(decision, sprintf \"revision %%d is stale; the stored revision is %%d\" expected current)" exT
    let unresolvedUsed = unresolvedScope || p.OnStale = StaleAction.Unresolved
    let escalatedUsed = session || p.OnStale = StaleAction.Escalate || durable
    let types =
        [ "/// The identity of one persisted instance. Its text is the host's; generated code only compares it."
          sprintf "type %s = %s of string" idT idT
          "" ]
        @ (if unresolvedScope then []
           else
               [ "/// The identity of one requested operation, chosen by the caller and stable across retries."
                 sprintf "type %s = %s of string" opT opT
                 "" ])
        @ [ (if durable then "/// A stored instance. `Applied` holds every operation id that has landed, so it survives reload."
             else "/// A stored instance.")
            "type " + recT + " ="
            sprintf "    { Id: %s" idT
            "      Revision: int64"
            (if durable then sprintf "      State: %s" st else sprintf "      State: %s }" st) ]
        @ (if durable then [ sprintf "      Applied: Set<%s> }" opT ] else [])
        @ [ "" ]
        @ union "What the store reports for a load. Unknown is a first-class outcome." loadT
            [ "Found of record: " + recT; "Missing"; "LoadUnknown of reason: string" ]
        @ union "What the store reports for a compare-and-swap save. Unknown is a first-class outcome, distinct from a definite failure." saveT
            [ "Saved"; "Stale of current: int64"; "SaveFailed of reason: string"; "SaveUnknown of reason: string" ]
        @ [ "/// The store a persisted instance lives in. Implemented by a host (Tier 4)."
            "type " + storeT + " ="
            sprintf "    abstract Load: id: %s -> %s" idT loadT
            sprintf "    abstract Save: expected: int64 * record: %s -> %s" recT saveT
            "" ]
    let execution =
        [ "/// The outcome of executing one command against the stored instance."
          "[<RequireQualifiedAccess>]"
          "type " + exT + " =" ]
        @ indent 4
            ([ "/// Decided and saved. `record` is the stored instance."
               sprintf "| Executed of decision: %s * record: %s" dt recT ]
             @ (if unresolvedScope then []
                else [ "/// The operation already landed; nothing was decided or written."
                       sprintf "| AlreadyApplied of operation: %s" opT ])
             @ [ "/// Tier 2 refused the command; nothing was written."
                 sprintf "| Refused of refusal: %s * record: %s" rf recT
                 "/// No stored instance has this id."
                 sprintf "| NotFound of id: %s" idT
                 "/// The store could not say whether the instance exists; nothing was decided."
                 sprintf "| LoadUnknown of id: %s * reason: string" idT
                 "/// Definitely not saved. The stored instance is unchanged, so the caller may try again."
                 sprintf "| NotSaved of decision: %s * reason: string" dt ]
             @ (if p.OnStale = StaleAction.Refuse then
                    [ "/// Another write landed first; the plan refuses a stale write. Nothing was written."
                      sprintf "| StaleRevision of decision: %s * expected: int64 * current: int64" dt ]
                else [])
             @ (if escalatedUsed then
                    [ "/// A person must decide: the outcome could not be settled, or the plan escalates it."
                      sprintf "| Escalated of decision: %s * reason: string" dt ]
                else [])
             @ (if unresolvedUsed then
                    [ "/// The plan leaves what this outcome means unresolved; a RESOLVE obligation records it."
                      sprintf "| Unresolved of decision: %s * reason: string" dt ]
                else []))
        @ [ "" ]
    let decideArgs =
        (if s.HasRules then [ "rules" ] else []) @ (if s.HasCapabilities then [ "held" ] else []) @ [ "record.State"; "command" ]
    let ruleParams =
        (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else []) @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
    let ruleArgs = (if s.HasRules then [ "rules" ] else []) @ (if s.HasCapabilities then [ "held" ] else [])
    let opParam = if unresolvedScope then "" else sprintf " (operation: %s)" opT
    let opArg = if unresolvedScope then "" else " operation"
    let nextRecord =
        if durable then "{ record with Revision = record.Revision + 1L; State = decision.Next; Applied = Set.add operation record.Applied }"
        else "{ record with Revision = record.Revision + 1L; State = decision.Next }"
    let stale =
        [ "/// What a write against a stale revision means, as the plan declares it."
          sprintf "let stale (decision: %s) (expected: int64) (current: int64) : %s =" dt exT
          "    " + staleCase
          "" ]
    let settle =
        if durable then
            [ "/// Settles an unknown save by reading the instance back. The operation landed if the stored"
              "/// instance records it; it did not if the revision is unchanged; a moved revision without it"
              "/// means another write won the compare-and-swap. Nothing is written again."
              sprintf "let settle (store: %s) (record: %s) (operation: %s) (decision: %s) (reason: string) : %s =" storeT recT opT dt exT
              "    match store.Load record.Id with"
              sprintf "    | %s.Found stored when Set.contains operation stored.Applied -> %s.Executed(decision, stored)" loadT exT
              sprintf "    | %s.Found stored when stored.Revision = record.Revision -> %s.NotSaved(decision, reason)" loadT exT
              sprintf "    | %s.Found stored -> stale decision record.Revision stored.Revision" loadT
              sprintf "    | %s.Missing | %s.LoadUnknown _ -> %s.Escalated(decision, reason)" loadT loadT exT
              "" ]
        else []
    let unknownSave =
        if durable then "settle store record operation decision reason"
        elif session then sprintf "%s.Escalated(decision, reason)" exT
        else sprintf "%s.Unresolved(decision, reason)" exT
    let save =
        [ "/// Saves the decided instance with a compare-and-swap on the revision it was decided against."
          sprintf "let save (store: %s) (record: %s)%s (decision: %s) : %s =" storeT recT opParam dt exT
          "    let next = " + nextRecord
          "    match store.Save(record.Revision, next) with"
          sprintf "    | %s.Saved -> %s.Executed(decision, next)" saveT exT
          sprintf "    | %s.SaveFailed reason -> %s.NotSaved(decision, reason)" saveT exT
          sprintf "    | %s.Stale current -> stale decision record.Revision current" saveT
          sprintf "    | %s.SaveUnknown reason -> %s" saveT unknownSave
          "" ]
    let decideAndSave =
        [ sprintf "    match %s.decide %s with" (transitionModule w) (String.concat " " decideArgs)
          sprintf "    | Error refusal -> %s.Refused(refusal, record)" exT
          sprintf "    | Ok decision -> save store record%s decision" opArg ]
    let execute =
        let parameters = [ sprintf "(store: %s)" storeT ] @ ruleParams
        if durable then
            [ "/// Executes one command: load, skip an operation that already landed, decide, save."
              sprintf "let execute %s (id: %s) (operation: %s) (command: %s) : %s =" (String.concat " " parameters) idT opT cmd exT
              "    match store.Load id with"
              sprintf "    | %s.Missing -> %s.NotFound id" loadT exT
              sprintf "    | %s.LoadUnknown reason -> %s.LoadUnknown(id, reason)" loadT exT
              sprintf "    | %s.Found record when Set.contains operation record.Applied -> %s.AlreadyApplied operation" loadT exT
              sprintf "    | %s.Found record -> decideAndSave store%s record operation command" loadT (ruleArgs |> List.map ((+) " ") |> String.concat "") ]
            |> fun lines ->
                [ "/// Decides the command against the loaded instance and saves the result."
                  sprintf "let decideAndSave %s (record: %s) (operation: %s) (command: %s) : %s =" (String.concat " " parameters) recT opT cmd exT ]
                @ decideAndSave @ [ "" ] @ lines
        elif session then
            [ "/// Executes one command. The caller holds this session's applied operation ids: they do not"
              "/// survive reload, so an unknown save is escalated rather than settled."
              sprintf "let execute %s (seen: Set<%s>) (id: %s) (operation: %s) (command: %s) : %s * Set<%s> =" (String.concat " " parameters) opT idT opT cmd exT opT
              "    if Set.contains operation seen then"
              sprintf "        %s.AlreadyApplied operation, seen" exT
              "    else"
              "        let result ="
              "            match store.Load id with"
              sprintf "            | %s.Missing -> %s.NotFound id" loadT exT
              sprintf "            | %s.LoadUnknown reason -> %s.LoadUnknown(id, reason)" loadT exT
              sprintf "            | %s.Found record -> decideAndSave store%s record operation command" loadT (ruleArgs |> List.map ((+) " ") |> String.concat "")
              "        match result with"
              sprintf "        | %s.Executed _ -> result, Set.add operation seen" exT
              "        | _ -> result, seen" ]
            |> fun lines ->
                [ "/// Decides the command against the loaded instance and saves the result."
                  sprintf "let decideAndSave %s (record: %s) (operation: %s) (command: %s) : %s =" (String.concat " " parameters) recT opT cmd exT ]
                @ decideAndSave @ [ "" ] @ lines
        else
            [ "/// Executes one command: load, decide, save. Operation ids are not deduplicated: the plan"
              "/// leaves the idempotency scope unresolved."
              sprintf "let execute %s (id: %s) (command: %s) : %s =" (String.concat " " parameters) idT cmd exT
              "    match store.Load id with"
              sprintf "    | %s.Missing -> %s.NotFound id" loadT exT
              sprintf "    | %s.LoadUnknown reason -> %s.LoadUnknown(id, reason)" loadT exT
              sprintf "    | %s.Found record ->" loadT ]
            @ indent 4 decideAndSave
    let codes =
        let assigned subject = s.Workflow.CodeAssignments |> List.tryFind (fun a -> a.Target = subject) |> Option.map _.Code
        if List.isEmpty s.Codes then []
        else
            let rc = refusalCodeType w
            let some code = code |> Option.map (fun c -> sprintf "Some %s" (qualify rc c)) |> Option.defaultValue "None"
            [ ""
              "/// The typed code of an execution outcome, as the plan assigns it; None where it assigns none."
              sprintf "let executionCode (execution: %s) : %s option =" exT rc
              "    match execution with"
              sprintf "    | %s.Refused(refusal, _) -> %s.refusalCode refusal" exT (transitionModule w)
              sprintf "    | %s.NotFound _ -> %s" exT (some (assigned CodeSubject.NotFound)) ]
            @ (if p.OnStale = StaleAction.Refuse then [ sprintf "    | %s.StaleRevision _ -> %s" exT (some (assigned CodeSubject.StaleRevision)) ] else [])
            @ [ sprintf "    | %s.Executed _" exT ]
            @ (if unresolvedScope then [] else [ sprintf "    | %s.AlreadyApplied _" exT ])
            @ [ sprintf "    | %s.LoadUnknown _" exT; sprintf "    | %s.NotSaved _" exT ]
            @ (if escalatedUsed then [ sprintf "    | %s.Escalated _" exT ] else [])
            @ (if unresolvedUsed then [ sprintf "    | %s.Unresolved _" exT ] else [])
            |> fun lines -> List.take (List.length lines - 1) lines @ [ List.last lines + " -> None" ]
    render (
        header s.Generator digest "Tier 3 (Persistence): loads, deduplicates, decides and saves one instance"
        @ [ "namespace " + rootNamespace w; "" ]
        @ types @ execution
        @ [ "/// Executes commands against the stored instance. Depends on Tiers 1 and 2 only."
            "[<RequireQualifiedAccess>]"
            "module " + persistenceModule w + " =" ]
        @ indent 4 ([ "" ] @ stale @ settle @ save @ execute @ codes))

// ---- Tier 3: Document (vocabulary 7) ----

/// Many instances of the workflow in one stored document. Commands change a
/// working copy in memory; `save` writes the whole document under one
/// caller-chosen operation id with a compare-and-swap on the document
/// version. A save whose outcome is unknown is returned as unknown and
/// blocks further changes until `reconcile` inspects the stored document; it
/// is never settled implicitly and never written again by generated code.
/// Depends on Tiers 1 and 2 only.
let document (digest: string) (s: Shape) (d: DocumentPersistence) =
    let w = s.Workflow.Name
    let st, cmd, dt, rf = stateType w, commandType w, decisionType w, refusalType w
    let idT, opT = idType w, operationIdType w
    let entryT, docT, readT, writeT, errT, storeT = entryType w, documentType w, documentReadType w, documentWriteType w, writeErrorType w, documentStoreType w
    let sessT, loadedT, createdT, outT, saveT, recT = documentSessionType w, documentLoadedType w, createdType w, commandOutcomeType w, saveOutcomeType w, reconciledType w
    let durable = d.Idempotency = IdempotencyScope.Durable
    let session = d.Idempotency = IdempotencyScope.Session
    let unresolvedScope = d.Idempotency = IdempotencyScope.Unresolved
    let deduplicates = not unresolvedScope
    let conflictCase (typeName: string) (refused: string) (current: string) =
        let reason = sprintf "sprintf \"another write moved the document to version %%A\" %s" current
        match d.OnSaveConflict with
        | StaleAction.Refuse -> sprintf "%s.%s %s" typeName refused current
        | StaleAction.Escalate -> sprintf "%s.Escalated(%s)" typeName reason
        | StaleAction.Unresolved -> sprintf "%s.Unresolved(%s)" typeName reason
    let escalatedOnSave = d.OnSaveConflict = StaleAction.Escalate
    let unresolvedOnSave = d.OnSaveConflict = StaleAction.Unresolved
    let escalatedOnReconcile = (durable && escalatedOnSave) || session
    let unresolvedOnReconcile = (durable && unresolvedOnSave) || unresolvedScope
    let initial = s.States |> List.head
    let types =
        [ "/// The identity of one entry in the document. Its text is the host's; generated code only compares it."
          sprintf "type %s = %s of string" idT idT
          ""
          "/// The identity of one save, chosen by the caller and stable across retries of that save."
          sprintf "type %s = %s of string" opT opT
          ""
          "/// One instance of the workflow inside the document. `Revision` counts its decided changes."
          "type " + entryT + " ="
          sprintf "    { Id: %s" idT
          "      Revision: int64"
          sprintf "      State: %s }" st
          "" ]
        @ [ "/// The stored document. `Version` is None until the first write lands."
            + (if durable then " `Applied` is kept by the store: every operation that landed, with the version it produced." else "")
            "type " + docT + " ="
            "    { Version: int64 option"
            (if durable then sprintf "      Entries: Map<%s, %s>" idT entryT else sprintf "      Entries: Map<%s, %s> }" idT entryT) ]
        @ (if durable then [ sprintf "      Applied: Map<%s, int64> }" opT ] else [])
        @ [ "" ]
        @ union "What the store reports for a read. A failed read is distinct from a missing document." readT
            [ "Found of document: " + docT; "Missing"; "ReadFailed of reason: string" ]
        @ [ "/// Why a write failed. Only a failure proven not to have applied is a definite failure."
            "type " + errT + " ="
            "    { Reason: string"
            "      ProvenNotApplied: bool }"
            "" ]
        @ union "What the store reports for a compare-and-swap write. Nothing is written on a mismatch." writeT
            [ "Written of version: int64"; "VersionMismatch of current: int64 option"; "WriteFailed of error: " + errT ]
        @ [ "/// The store the document lives in. Implemented by a host (Tier 4)."
            "type " + storeT + " ="
            "    abstract Read: unit -> " + readT
            sprintf "    abstract Write: operation: %s * expected: int64 option * document: %s -> %s" opT docT writeT
            "" ]
        @ [ "/// One caller's view of the document: what was last read or confirmed written, the working"
            "/// copy with changes applied in memory, and a save whose outcome is not yet known."
            "type " + sessT + " ="
            sprintf "    { Stored: %s" docT
            sprintf "      Working: %s" docT ]
        @ (if session then [ sprintf "      Confirmed: Map<%s, int64>" opT ] else [])
        @ [ sprintf "      Pending: %s option }" opT; "" ]
        @ union "What loading the document reports. A missing document starts empty and is created by the first save." loadedT
            [ "Loaded of session: " + sessT; "DocumentMissing of session: " + sessT; "LoadFailed of reason: string" ]
        @ union "What adding an entry at the initial state reports." createdT
            [ "Created of session: " + sessT; "AlreadyExists of id: " + idT; "Unreconciled of pending: " + opT ]
        @ union "What applying one command to one entry in memory reports. Nothing is written." outT
            [ sprintf "Applied of session: %s * decision: %s" sessT dt
              sprintf "Refused of refusal: %s * entry: %s" rf entryT
              "EntryNotFound of id: " + idT
              sprintf "EntryStale of id: %s * expected: int64 * current: int64" idT
              "Unreconciled of pending: " + opT ]
        @ union "What a save reports. An unknown outcome is never collapsed into success or failure." saveT
            ([ sprintf "Saved of operation: %s * version: int64" opT ]
             @ (if deduplicates then [ sprintf "AlreadySaved of operation: %s * version: int64" opT ] else [])
             @ [ "NotSaved of reason: string" ]
             @ (if d.OnSaveConflict = StaleAction.Refuse then [ "SaveConflict of current: int64 option" ] else [])
             @ (if escalatedOnSave then [ "Escalated of reason: string" ] else [])
             @ (if unresolvedOnSave then [ "Unresolved of reason: string" ] else [])
             @ [ "OutcomeUnknown of operation: " + opT; "Unreconciled of pending: " + opT ])
        @ union "What inspecting the stored document reports about one save." recT
            ((if deduplicates then [ "Applied of version: int64" ] else [])
             @ [ "NotApplied" ]
             @ (if durable && d.OnSaveConflict = StaleAction.Refuse then [ "ReconcileConflict of current: int64 option" ] else [])
             @ (if escalatedOnReconcile then [ "Escalated of reason: string" ] else [])
             @ (if unresolvedOnReconcile then [ "Unresolved of reason: string" ] else [])
             @ [ "StillUnknown of reason: string" ])
    let empty =
        [ "/// The document before its first write."
          sprintf "let empty : %s =" docT
          "    { Version = None"
          (if durable then "      Entries = Map.empty" else "      Entries = Map.empty }") ]
        @ (if durable then [ "      Applied = Map.empty }" ] else [])
        @ [ "" ]
        @ [ "/// A session over a document just read."
            sprintf "let start (document: %s) : %s =" docT sessT
            (if session then "    { Stored = document; Working = document; Confirmed = Map.empty; Pending = None }"
             else "    { Stored = document; Working = document; Pending = None }")
            "" ]
    let load =
        [ "/// Reads the document and starts a session over it."
          sprintf "let load (store: %s) : %s =" storeT loadedT
          "    match store.Read() with"
          sprintf "    | %s.Found document -> %s.Loaded(start document)" readT loadedT
          sprintf "    | %s.Missing -> %s.DocumentMissing(start empty)" readT loadedT
          sprintf "    | %s.ReadFailed reason -> %s.LoadFailed reason" readT loadedT
          "" ]
    let withEntry =
        [ "let private withEntry (session: " + sessT + ") (entry: " + entryT + ") ="
          "    { session with Working = { session.Working with Entries = Map.add entry.Id entry session.Working.Entries } }"
          "" ]
    let create =
        [ "/// Adds an entry at the workflow's initial state, in memory. Refused while a save is unknown."
          sprintf "let create (session: %s) (id: %s) : %s =" sessT idT createdT
          "    match session.Pending with"
          sprintf "    | Some pending -> %s.Unreconciled pending" createdT
          sprintf "    | None when Map.containsKey id session.Working.Entries -> %s.AlreadyExists id" createdT
          sprintf "    | None -> %s.Created(withEntry session { Id = id; Revision = 0L; State = %s })" createdT (qualify st initial)
          "" ]
    let ruleParams =
        (if s.HasRules then [ sprintf "(rules: %s)" (rulesType w) ] else []) @ (if s.HasCapabilities then [ "(held: Set<string>)" ] else [])
    let decideArgs =
        (if s.HasRules then [ "rules" ] else []) @ (if s.HasCapabilities then [ "held" ] else []) @ [ "entry.State"; "command" ]
    let apply =
        [ "/// Decides one command against one entry and applies it to the working copy. `expected`, when"
          "/// given, is the entry revision the caller acted on. Refused while a save is unknown."
          sprintf "let apply %s(session: %s) (id: %s) (expected: int64 option) (command: %s) : %s ="
              (ruleParams |> List.map (fun p -> p + " ") |> String.concat "") sessT idT cmd outT
          "    match session.Pending, Map.tryFind id session.Working.Entries, expected with"
          sprintf "    | Some pending, _, _ -> %s.Unreconciled pending" outT
          sprintf "    | None, None, _ -> %s.EntryNotFound id" outT
          sprintf "    | None, Some entry, Some revision when revision <> entry.Revision -> %s.EntryStale(id, revision, entry.Revision)" outT
          "    | None, Some entry, _ ->"
          sprintf "        match %s.decide %s with" (transitionModule w) (String.concat " " decideArgs)
          sprintf "        | Error refusal -> %s.Refused(refusal, entry)" outT
          "        | Ok decision ->"
          sprintf "            %s.Applied(withEntry session { entry with Revision = entry.Revision + 1L; State = decision.Next }, decision)" outT
          "" ]
    let write =
        let stored =
            if durable then "{ session.Working with Version = Some version; Applied = Map.add operation version session.Working.Applied }"
            else "{ session.Working with Version = Some version }"
        let confirmed = if session then "; Confirmed = Map.add operation version session.Confirmed" else ""
        [ "let private write (store: " + storeT + ") (session: " + sessT + ") (operation: " + opT + ") ="
          "    match store.Write(operation, session.Stored.Version, session.Working) with"
          sprintf "    | %s.Written version ->" writeT
          "        let stored = " + stored
          sprintf "        %s.Saved(operation, version), { session with Stored = stored; Working = stored%s }" saveT confirmed
          sprintf "    | %s.VersionMismatch current -> %s, session" writeT (conflictCase saveT "SaveConflict" "current")
          sprintf "    | %s.WriteFailed error when error.ProvenNotApplied -> %s.NotSaved error.Reason, session" writeT saveT
          sprintf "    | %s.WriteFailed _ -> %s.OutcomeUnknown operation, { session with Pending = Some operation }" writeT saveT
          "" ]
    let save =
        let applied = if durable then Some "session.Stored.Applied" elif session then Some "session.Confirmed" else None
        [ "/// Writes the working copy under `operation`, expecting the version last read or written. A"
          "/// failure not proven to be without effect is unknown: it is returned as unknown and blocks"
          "/// further changes until `reconcile` inspects the stored document."
          sprintf "let save (store: %s) (session: %s) (operation: %s) : %s * %s =" storeT sessT opT saveT sessT ]
        @ (match applied with
           | Some applied ->
               [ sprintf "    match session.Pending, Map.tryFind operation %s with" applied
                 sprintf "    | Some pending, _ -> %s.Unreconciled pending, session" saveT
                 sprintf "    | None, Some version -> %s.AlreadySaved(operation, version), session" saveT
                 "    | None, None -> write store session operation" ]
           | None ->
               [ "    match session.Pending with"
                 sprintf "    | Some pending -> %s.Unreconciled pending, session" saveT
                 "    | None -> write store session operation" ])
        @ [ "" ]
    let reconcile =
        let moved =
            if durable then conflictCase recT "ReconcileConflict" "current.Version"
            elif session then sprintf "%s.Escalated \"the document moved and this session cannot tell whether the operation landed\"" recT
            else sprintf "%s.Unresolved \"the document moved and the plan leaves the idempotency scope unresolved\"" recT
        let movedSession = if durable && d.OnSaveConflict = StaleAction.Refuse then "settled" else "session"
        let inspect =
            [ "let private inspect (store: " + storeT + ") (session: " + sessT + ") (operation: " + opT + ") ="
              "    let settled = { session with Pending = if session.Pending = Some operation then None else session.Pending }"
              "    match store.Read() with"
              sprintf "    | %s.ReadFailed reason -> %s.StillUnknown reason, session" readT recT
              "    | read ->"
              sprintf "        let current = match read with | %s.Found document -> document | _ -> empty" readT ]
            @ (if durable then
                   [ "        match Map.tryFind operation current.Applied with"
                     sprintf "        | Some version -> %s.Applied version, { settled with Stored = current; Working = current }" recT
                     sprintf "        | None when current.Version = session.Stored.Version -> %s.NotApplied, settled" recT
                     sprintf "        | None -> %s, %s" moved movedSession ]
               else
                   [ sprintf "        if current.Version = session.Stored.Version then %s.NotApplied, settled" recT
                     sprintf "        else %s, %s" moved movedSession ])
            @ [ "" ]
        inspect
        @ [ "/// Inspects the stored document to settle one save whose outcome was unknown. Nothing is written."
            sprintf "let reconcile (store: %s) (session: %s) (operation: %s) : %s * %s =" storeT sessT opT recT sessT ]
        @ (if session then
               [ "    match Map.tryFind operation session.Confirmed with"
                 sprintf "    | Some version -> %s.Applied version, { session with Pending = None }" recT
                 "    | None -> inspect store session operation" ]
           else [ "    inspect store session operation" ])
        @ [ "" ]
    let codes =
        let assigned subject = s.Workflow.CodeAssignments |> List.tryFind (fun a -> a.Target = subject) |> Option.map _.Code
        if List.isEmpty s.Codes then []
        else
            let rc = refusalCodeType w
            let some code = code |> Option.map (fun c -> sprintf "Some %s" (qualify rc c)) |> Option.defaultValue "None"
            [ "/// The typed code of a command outcome, as the plan assigns it; None where it assigns none."
              sprintf "let commandCode (outcome: %s) : %s option =" outT rc
              "    match outcome with"
              sprintf "    | %s.Refused(refusal, _) -> %s.refusalCode refusal" outT (transitionModule w)
              sprintf "    | %s.EntryNotFound _ -> %s" outT (some (assigned CodeSubject.NotFound))
              sprintf "    | %s.EntryStale _ -> %s" outT (some (assigned CodeSubject.StaleRevision))
              sprintf "    | %s.Applied _ | %s.Unreconciled _ -> None" outT outT ]
            @ (if d.OnSaveConflict = StaleAction.Refuse then
                   [ ""
                     "/// The typed code of a save outcome, as the plan assigns it; None where it assigns none."
                     sprintf "let saveCode (outcome: %s) : %s option =" saveT rc
                     "    match outcome with"
                     sprintf "    | %s.SaveConflict _ -> %s" saveT (some (assigned CodeSubject.SaveConflict))
                     "    | _ -> None" ]
               else [])
    render (
        header s.Generator digest "Tier 3 (Document): applies commands in memory, saves and reconciles the document"
        @ [ "namespace " + rootNamespace w; "" ]
        @ types
        @ [ "/// Works on the document. Depends on Tiers 1 and 2 only."
            "[<RequireQualifiedAccess>]"
            "module " + documentModule w + " =" ]
        @ indent 4 ([ "" ] @ empty @ load @ withEntry @ create @ apply @ write @ save @ reconcile @ codes))
